def astro(label):
    s = str(label).strip()
    if "π.Χ" in s or "πΧ" in s:
        m = re.match(r"(\d+)", s)
        if not m:
            return -10**9
        b = int(m.group(1))
        return -(b - 1) if b > 1 else 0
    m = re.match(r"^(\d+)", s)
    return int(m.group(1)) if m else -10**9


